function runCommand(command, args, options = {}) {
  const isWindows = process.platform === "win32";
  const shell = isWindows ? true : false;

  return spawn(command, args, {
    stdio: options.stdio || "inherit",
    shell,
    cwd: options.cwd || process.cwd(),
    env: { ...process.env, ...options.env },
    detached: options.detached || false,
  });
}

function runCommandSync(command, options = {}) {
  try {
    return execSync(command, {
      stdio: options.stdio || "pipe",
      encoding: "utf-8",
      cwd: options.cwd || process.cwd(),
    });
  } catch (error) {
    return null;
  }
}

function commandExists(command) {
  const isWindows = process.platform === "win32";
  const lookupCommand = isWindows ? `where ${command}` : `command -v ${command}`;
  return Boolean(runCommandSync(lookupCommand, { stdio: "pipe" }));
}

function normalizeVersion(version) {
  return version.replace(/^v/, "").trim();
}

function compareVersions(a, b) {
  const aParts = normalizeVersion(a).split(".").map(Number);
  const bParts = normalizeVersion(b).split(".").map(Number);
  const maxLength = Math.max(aParts.length, bParts.length);

  for (let index = 0; index < maxLength; index += 1) {
    const aPart = aParts[index] ?? 0;
    const bPart = bParts[index] ?? 0;

    if (aPart > bPart) return 1;
    if (aPart < bPart) return -1;
  }

  return 0;
}

function getCommandVersion(command, versionArgs = ["--version"]) {
  const output = runCommandSync(`${command} ${versionArgs.join(" ")}`, {
    stdio: "pipe",
  });

  if (!output) {
    return null;
  }

  const firstLine = output.split(/\r?\n/).find((line) => line.trim().length > 0);
  return firstLine?.trim() ?? null;
}

function runPreflightChecks({ useDocker }) {
  log.step(1, 4, "Running preflight checks...");

  const failures = [];
  const nodeVersion = normalizeVersion(process.version);
  const npmVersion = getCommandVersion("npm");
  const supabaseVersion = getCommandVersion("npx", ["supabase", "--version"]);
  // const supabaseVersion = getCommandVersion("supabase", ["--version"]);
  const dockerVersion = commandExists("docker")
    ? getCommandVersion("docker", ["--version"])
    : null;

  if (compareVersions(nodeVersion, CONFIG.requiredNodeVersion) !== 0) {
    failures.push(
      `Node.js ${CONFIG.requiredNodeVersion} is required, found ${nodeVersion}`,
    );
  }

  if (!npmVersion) {
    failures.push("npm is required but was not found in PATH");
  }

  if (!supabaseVersion) {
    failures.push(
      "Supabase CLI is required. Install it or ensure `npx supabase --version` works.",
    );
  }

  if (!commandExists("docker")) {
    failures.push("Docker is required but was not found in PATH");
  }

  if (useDocker && !isDockerComposeAvailable()) {
    failures.push("Docker Compose is required for --docker mode");
  }

  if (failures.length > 0) {
    failures.forEach((failure) => log.error(failure));
    return false;
  }

  log.success(`Node.js ${nodeVersion}`);
  log.success(`npm ${npmVersion}`);
  log.success(`Supabase CLI ${supabaseVersion}`);
  log.success(dockerVersion ? dockerVersion : "Docker available");
  return true;
}

function didCommandSucceed(command, options = {}) {
  try {
    execSync(command, {
      stdio: options.stdio || "inherit",
      encoding: "utf-8",
      cwd: options.cwd || process.cwd(),
    });
    return true;
  } catch (error) {
    return false;
  }
}

function isDockerComposeAvailable() {
  return didCommandSucceed("docker compose version", { stdio: "pipe" });
}

function hasDockerComposeServices() {
  if (!isDockerComposeAvailable()) {
    return false;
  }

  const output = runCommandSync("docker compose ps -q", { stdio: "pipe" });
  return Boolean(output?.trim());
}

