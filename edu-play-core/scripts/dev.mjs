let nextjsProcess = null;

async function killNextjsProcesses() {
  log.info("Checking for Next.js processes...");

  const isWindows = process.platform === "win32";
  const port = CONFIG.nextjs.port;

  if (isWindows) {
    const netstatOutput = runCommandSync(`netstat -ano | findstr ":${port}"`, {
      stdio: "pipe",
    });

    if (netstatOutput) {
      // Extract PIDs from netstat output
      const pidMatches = netstatOutput.matchAll(/LISTENING\s+(\d+)/g);
      const pids = [...new Set([...pidMatches].map((match) => match[1]))];

      if (pids.length > 0) {
        log.info(
          `Found ${pids.length} process(es) on port ${port}: ${pids.join(", ")}`,
        );
        pids.forEach((pid) => {
          log.info(`Killing process ${pid}...`);
          runCommandSync(`taskkill /F /PID ${pid}`, { stdio: "pipe" });
        });
        log.success("Next.js processes stopped");
      } else {
        log.info("No Next.js processes found");
      }
    } else {
      log.info(`No processes found on port ${port}`);
    }
  } else {
    // Unix-like systems
    const output = runCommandSync(`lsof -tiTCP:${port} -sTCP:LISTEN`, {
      stdio: "pipe",
    });
    if (output) {
      const pids = output.trim().split("\n").filter(Boolean);
      pids.forEach((pid) => {
        log.info(`Killing process ${pid}...`);
        runCommandSync(`kill -9 ${pid}`, { stdio: "pipe" });
      });
      log.success("Next.js processes stopped");
    } else {
      log.info("No Next.js processes found");
    }
  }

  // Clean up lock file if it exists
  const lockPath = ".next/dev/lock";
  try {
    if (fs.existsSync(lockPath)) {
      fs.unlinkSync(lockPath);
      log.success("Removed stale lock file");
    }
  } catch (error) {
    // Ignore errors
  }

  removeNextjsOwnershipFile();

  return !isPortInUse(port);
}

async function startNextjs() {
  log.step(4, 4, "Starting Next.js development server...");

  const managedNextjs = getManagedNextjsProcess();
  if (managedNextjs) {
    log.info(
      `Found managed Next.js process ${managedNextjs.pid}; validating server ownership...`,
    );

    if (await isNextjsRunning()) {
      log.success(`Next.js is already running on port ${CONFIG.nextjs.port}`);
      return true;
    }

    log.info("Managed Next.js process exists but has not passed the probe yet");
    const ready = await waitForService("Next.js", isNextjsRunning, 30000);

    if (ready) {
      log.success("Next.js is now responding");
      return true;
    }

    log.error(
      "Managed Next.js process did not pass the Next.js probe. Stop it and try again.",
    );
    return false;
  }

  // First check if port is in use
  const portInUse = isPortInUse(CONFIG.nextjs.port);

  if (portInUse) {
    // Port is in use - check if it's responding
    if (await isNextjsRunning()) {
      log.success(`Next.js is already running on port ${CONFIG.nextjs.port}`);
      return true;
    } else {
      // Port is in use but has not passed the Next.js probe yet
      log.warn(
        `Port ${CONFIG.nextjs.port} is in use but has not passed the Next.js probe`,
      );
      log.info(
        `Waiting to see if the existing process on port ${CONFIG.nextjs.port} becomes a valid Next.js server`,
      );
      log.info("If this is a stale process, stop it with: npm run dev:stop");

      // Wait a bit to see if it starts responding
      log.info("Waiting for Next.js to respond...");
      const ready = await waitForService("Next.js", isNextjsRunning, 30000);

      if (ready) {
        log.success("Next.js is now responding");
        return true;
      } else {
        log.error(
          "Next.js is not responding. Please stop the existing process and try again.",
        );
        log.error("Use npm run dev:stop to clean up the stale process");
        return false;
      }
    }
  }

  // Port is free - start a new Next.js process
  nextjsProcess = runCommand(
    "npm",
    ["run", "dev", "--", "--port", String(CONFIG.nextjs.port)],
    {
      stdio: "inherit",
      env: {
        FORCE_COLOR: "1",
      },
    },
  );

  writeNextjsOwnershipFile(nextjsProcess.pid);
  nextjsProcess.on("close", () => {
    removeNextjsOwnershipFile();
    nextjsProcess = null;
  });

  // Wait for Next.js to be ready
  const ready = await waitForService("Next.js", isNextjsRunning);

  if (ready) {
    log.success("Next.js development server started");
  }

  return ready;
}

