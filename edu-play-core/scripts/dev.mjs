async function main() {
  const args = process.argv.slice(2);
  const useDocker = args.includes("--docker");
  const skipNext = args.includes("--skip-next");
  const action = args.find((a) => !a.startsWith("--")) || "start";

  // Handle stop action
  if (action === "stop") {
    log.header("Stopping EduPlay Development Environment");

    const success = useDocker
      ? await stopDocker()
      : await stopManagedServices();

    if (!success) {
      log.error("Failed to stop all requested services");
      process.exit(1);
    }

    log.success("All services stopped");
    process.exit(0);
  }

  // Handle status action
  if (action === "status") {
    log.header("EduPlay Service Status");

    const supabase = await isSupabaseRunning({ useDocker });
    const nextjs = await isNextjsRunning();

    console.log(
      `  Supabase API:  ${supabase ? colors.green + "Running" : colors.red + "Stopped"}${colors.reset}`,
    );
    console.log(
      `  Next.js:       ${nextjs ? colors.green + "Running" : colors.red + "Stopped"}${colors.reset}`,
    );
    console.log("");

    process.exit(supabase && nextjs ? 0 : 1);
  }

  // Start action
  log.header("Starting EduPlay Development Environment");

  const preflightOk = runPreflightChecks({ useDocker });
  if (!preflightOk) {
    log.error("Preflight checks failed");
    process.exit(1);
  }

  if (useDocker) {
    log.info("Mode: Docker Compose (full stack)");
    const success = await startDocker();

    if (!success) {
      log.error("Failed to start development environment");
      process.exit(1);
    }
  } else {
    log.info("Mode: Supabase CLI + Next.js");

    // Start Supabase
    const supabaseOk = await startSupabase();
    if (!supabaseOk) {
      log.error("Failed to start Supabase");
      process.exit(1);
    }

    log.step(3, 4, "Preparing local environment variables...");
    const envReady = ensureLocalEnvFromRunningSupabase();
    if (!envReady.ok) {
      log.error("Failed to prepare local environment variables for Next.js");
      process.exit(1);
    }

    // Start Next.js (unless skipped)
    if (!skipNext) {
      const nextjsOk = await startNextjs();
      if (!nextjsOk) {
        log.error("Failed to start Next.js");
        process.exit(1);
      }
    }
  }

  // Print success message
  log.step(4, 4, "Environment ready!");
  console.log("");
  console.log(
    `  ${colors.bold}Application:${colors.reset}     ${getNextjsUrl()}`,
  );
  console.log(
    `  ${colors.bold}Supabase API:${colors.reset}    http://localhost:54421`,
  );
  console.log(
    `  ${colors.bold}Supabase Studio:${colors.reset} http://localhost:54423`,
  );
  console.log(
    `  ${colors.bold}Email Testing:${colors.reset}   http://localhost:54424`,
  );
  console.log("");
  console.log(`  ${colors.dim}Stop with: npm run dev:stop${colors.reset}`);
  console.log("");

  // Keep process running if Next.js is running in foreground
  if (!useDocker && !skipNext && nextjsProcess) {
    // Forward signals to child process
    ["SIGINT", "SIGTERM"].forEach((signal) => {
      process.on(signal, () => {
        if (nextjsProcess) {
          nextjsProcess.kill(signal);
        }
        process.exit(0);
      });
    });
  }
}

main().catch((error) => {
  log.error(error.message);
  process.exit(1);
});
