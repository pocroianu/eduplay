async function startSupabase() {
  log.step(2, 4, "Starting Supabase services...");

  // Check if already running
  if (await isSupabaseRunning()) {
    log.success("Supabase is already running");
    return true;
  }

  // Start Supabase
  const supabaseProc = runCommand("npx", ["supabase", "start"], {
    stdio: "inherit",
  });

  return new Promise((resolve) => {
    supabaseProc.once("error", (err) => {
      log.error(`Failed to launch Supabase start command: ${err.message}`);
      resolve(false);
    });

    supabaseProc.once("close", async (code) => {
      if (code === 0) {
        if (!(await isSupabaseRunning())) {
          logSupabaseHostAccessFailure();
          resolve(false);
          return;
        }

        log.success("Supabase services started");
        resolve(true);
      } else {
        log.error("Failed to start Supabase");
        resolve(false);
      }
    });
  });
}

async function stopSupabase() {
  log.info("Stopping Supabase services...");

  const stopped = didCommandSucceed("npx supabase stop", { stdio: "inherit" });

  if (stopped) {
    log.success("Supabase stopped");
    return true;
  }

  log.error("Failed to stop Supabase");
  return false;
}

function isSupabaseCliStackPresent() {
  const output = runCommandSync("npx supabase status -o env", {
    stdio: "pipe",
  });
  return hasSupabaseCliStack(output);
}

