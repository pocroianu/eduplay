async function startDocker() {
  log.step(2, 4, "Starting Docker Compose services...");

  const proc = runCommand("docker", ["compose", "up", "-d"], {
    stdio: "inherit",
  });

  return new Promise((resolve) => {
    proc.once("error", (err) => {
      log.error(`Failed to launch Docker Compose command: ${err.message}`);
      resolve(false);
    });

    proc.once("close", async (code) => {
      if (code === 0) {
        log.success("Docker services started");

        // Wait for services to be healthy
        log.step(3, 4, "Waiting for services to be ready...");

        const supabaseReady = await waitForService(
          "Supabase",
          () => isSupabaseRunning({ useDocker: true }),
        );
        const nextjsReady = await waitForService("Next.js", isNextjsRunning);

        resolve(supabaseReady && nextjsReady);
      } else {
        log.error("Failed to start Docker services");
        resolve(false);
      }
    });
  });
}

async function stopDocker() {
  log.info("Stopping Docker Compose services...");

  if (!isDockerComposeAvailable()) {
    log.error("Docker Compose is not available");
    return false;
  }

  if (!hasDockerComposeServices()) {
    log.info("No Docker Compose services found for this project");
    return true;
  }

  const stopped = didCommandSucceed("docker compose down", {
    stdio: "inherit",
  });

  if (stopped) {
    log.success("Docker services stopped");
    return true;
  }

  log.error("Failed to stop Docker services");
  return false;
}

async function stopManagedServices() {
  let success = true;

  if (hasDockerComposeServices()) {
    success = (await stopDocker()) && success;
  }

  if (isSupabaseCliStackPresent()) {
    success = (await stopSupabase()) && success;
  }

  if (!hasDockerComposeServices() && isPortInUse(CONFIG.nextjs.port)) {
    success = (await killNextjsProcesses()) && success;
  }

  return success;
}

