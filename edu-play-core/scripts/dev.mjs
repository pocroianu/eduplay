async function requestUrl(
  url,
  { method = "GET", timeout = 5000, headers } = {},
) {
  return new Promise((resolve) => {
    const urlObj = new URL(url);
    const req = http.request(
      {
        hostname: urlObj.hostname,
        port: urlObj.port,
        path: `${urlObj.pathname}${urlObj.search}`,
        method,
        headers,
        timeout,
      },
      (res) => {
        let body = "";
        res.setEncoding("utf8");
        res.on("data", (chunk) => {
          if (body.length < 16_384) {
            body += chunk;
          }
        });
        res.on("end", () => {
          resolve({
            statusCode: res.statusCode ?? 0,
            headers: res.headers,
            body,
          });
        });
      },
    );
    req.on("error", () => resolve(null));
    req.on("timeout", () => {
      req.destroy();
      resolve(null);
    });
    req.end();
  });
}

async function checkUrl(url, timeout = 5000) {
  const response = await requestUrl(url, { method: "HEAD", timeout });
  return Boolean(
    response && response.statusCode >= 200 && response.statusCode < 500,
  );
}

function isPortInUse(port) {
  const isWindows = process.platform === "win32";
  const command = isWindows
    ? `netstat -ano | findstr LISTENING | findstr ":${port}"`
    : `lsof -nP -iTCP:${port} -sTCP:LISTEN`;

  const output = runCommandSync(command, { stdio: "pipe" });
  return output && output.trim().length > 0;
}

async function isSupabaseRunning({ useDocker = false } = {}) {
  return isSupabaseApiReady(CONFIG.supabase.apiUrl, requestUrl, {
    apiKey: getSupabaseProbeAnonKey({ useDocker }),
  });
}

function getSupabaseProbeAnonKey({ useDocker = false } = {}) {
  const envKey =
    process.env.SUPABASE_ANON_KEY ??
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (envKey) {
    return envKey;
  }

  if (useDocker) {
    const composeEnvKey = getComposeProjectAnonKeyFromEnvFile();
    if (composeEnvKey) {
      return composeEnvKey;
    }
  }

  const output = runCommandSync("npx supabase status -o env", {
    stdio: "pipe",
  });
  return getSupabaseStatusAnonKey(output);
}

function getComposeProjectAnonKeyFromEnvFile() {
  const envFilePath = path.resolve(".env");
  if (!fs.existsSync(envFilePath)) {
    return null;
  }

  try {
    return getComposeProjectEnvAnonKey(fs.readFileSync(envFilePath, "utf8"));
  } catch (error) {
    return null;
  }
}

function logSupabaseHostAccessFailure() {
  log.error(
    `Supabase API is not reachable from the host at ${getSupabaseApiHealthUrl(
      CONFIG.supabase.apiUrl,
    )}`,
  );
  log.error(
    "Docker/Supabase containers may be healthy internally while the Windows host port is not forwarding HTTP traffic.",
  );
  log.info("Try: npm run dev:stop");
  log.info("Then restart Docker Desktop or WSL networking.");
  log.info("Finally rerun: npm run dev:full");
}

function getNextjsUrl() {
  return `http://localhost:${CONFIG.nextjs.port}`;
}

function getNextjsOwnershipFilePath() {
  return path.resolve(CONFIG.nextjs.ownershipFile);
}

function getHeaderValue(headers, name) {
  const value = headers[name.toLowerCase()];
  if (Array.isArray(value)) {
    return value.join(", ");
  }
  return value ?? "";
}

function getManagedLocalEnvFilePath() {
  return path.resolve(CONFIG.env.localFile);
}

function isManagedLocalEnvFile(content) {
  return content.includes(CONFIG.env.managedHeader);
}

function parseSupabaseStatusEnv(output) {
  const values = {};

  for (const line of output.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (!match) {
      continue;
    }

    const [, key, rawValue] = match;
    let value = rawValue.trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    values[key] = value;
  }

  return values;
}

function formatEnvValue(value) {
  return JSON.stringify(value ?? "");
}

function buildManagedLocalEnvContent(values) {
  return `${CONFIG.env.managedHeader}
# Safe to delete; npm run dev:full will recreate it for local Supabase CLI usage.
# Commit a separate .env/.env.local only when you intentionally want non-local overrides.

NEXT_PUBLIC_SUPABASE_URL=${formatEnvValue(values.API_URL)}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${formatEnvValue(values.ANON_KEY)}
SUPABASE_SERVICE_ROLE_KEY=${formatEnvValue(values.SERVICE_ROLE_KEY)}
NEXT_PUBLIC_APP_URL=${formatEnvValue(`http://localhost:${CONFIG.nextjs.port}`)}
NODE_ENV=${formatEnvValue("development")}
`;
}

function ensureLocalEnvFromRunningSupabase() {
  const output = runCommandSync("npx supabase status -o env", { stdio: "pipe" });
  if (!output) {
    log.error("Could not read Supabase local environment values");
    return { ok: false, mode: "error" };
  }

  const values = parseSupabaseStatusEnv(output);
  const requiredKeys = ["API_URL", "ANON_KEY", "SERVICE_ROLE_KEY"];
  const missingKeys = requiredKeys.filter((key) => !values[key]);

  if (missingKeys.length > 0) {
    log.error(
      `Supabase status did not return required keys: ${missingKeys.join(", ")}`,
    );
    return { ok: false, mode: "error" };
  }

  const envFilePath = getManagedLocalEnvFilePath();
  const nextContent = buildManagedLocalEnvContent(values);

  if (fs.existsSync(envFilePath)) {
    const existingContent = fs.readFileSync(envFilePath, "utf8");

    if (!isManagedLocalEnvFile(existingContent)) {
      log.info(
        `Using existing custom ${CONFIG.env.localFile}; dev.mjs will not overwrite it`,
      );
      return { ok: true, mode: "custom" };
    }

    if (existingContent === nextContent) {
      log.success(
        `${CONFIG.env.localFile} already matches local Supabase (generated file reused)`,
      );
      return { ok: true, mode: "reused" };
    }
  }

  fs.writeFileSync(envFilePath, nextContent);
  log.success(
    `Generated ${CONFIG.env.localFile} from local Supabase credentials`,
  );
  return { ok: true, mode: "generated" };
}

function responseLooksLikeNextjs(response) {
  if (!response) {
    return false;
  }

  const isHttpSuccess =
    response.statusCode >= 200 && response.statusCode < 500;
  if (!isHttpSuccess) {
    return false;
  }

  const poweredBy = getHeaderValue(response.headers, "x-powered-by");
  const body = response.body ?? "";

  return (
    poweredBy.toLowerCase().includes("next.js") ||
    body.includes("/_next/") ||
    body.includes("__NEXT_DATA__")
  );
}

async function isNextjsRunning() {
  const response = await requestUrl(getNextjsUrl(), {
    method: "GET",
  });
  return responseLooksLikeNextjs(response);
}

function isProcessAlive(pid) {
  if (!Number.isInteger(pid) || pid <= 0) {
    return false;
  }

  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return false;
  }
}

function removeNextjsOwnershipFile() {
  try {
    const ownershipFile = getNextjsOwnershipFilePath();
    if (fs.existsSync(ownershipFile)) {
      fs.unlinkSync(ownershipFile);
    }
  } catch (error) {
    // Ignore cleanup failures
  }
}

function writeNextjsOwnershipFile(pid) {
  if (!Number.isInteger(pid) || pid <= 0) {
    return;
  }

  const ownershipFile = getNextjsOwnershipFilePath();
  fs.mkdirSync(path.dirname(ownershipFile), { recursive: true });
  fs.writeFileSync(
    ownershipFile,
    JSON.stringify(
      {
        pid,
        port: CONFIG.nextjs.port,
        createdAt: new Date().toISOString(),
      },
      null,
      2,
    ),
  );
}

function getManagedNextjsProcess() {
  const ownershipFile = getNextjsOwnershipFilePath();
  if (!fs.existsSync(ownershipFile)) {
    return null;
  }

  try {
    const parsed = JSON.parse(fs.readFileSync(ownershipFile, "utf8"));
    if (
      parsed.port !== CONFIG.nextjs.port ||
      !isProcessAlive(parsed.pid)
    ) {
      removeNextjsOwnershipFile();
      return null;
    }

    return parsed;
  } catch (error) {
    removeNextjsOwnershipFile();
    return null;
  }
}

async function waitForService(
  name,
  checkFn,
  maxWait = CONFIG.healthCheck.timeout,
) {
  const startTime = Date.now();
  const interval = CONFIG.healthCheck.interval;

  process.stdout.write(`   Waiting for ${name}`);

  while (Date.now() - startTime < maxWait) {
    if (await checkFn()) {
      console.log(` ${colors.green}✓${colors.reset}`);
      return true;
    }
    process.stdout.write(".");
    await sleep(interval);
  }

  console.log(` ${colors.red}✗${colors.reset}`);
  return false;
}

