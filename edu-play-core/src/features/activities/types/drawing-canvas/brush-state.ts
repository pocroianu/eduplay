// Drawing Canvas — pure brush + stroke state reducer.
//
// Lives outside the renderer so vitest can drive it without React or a DOM.
// The renderer pipes pointer events into `dispatch(action)`, then reads
// `state.strokes` to repaint the canvas. Undo/redo granularity = per-stroke
// (a stroke is "pointerdown → pointerup"), per EDU-293 § 5.

import {
  DEFAULT_BRUSH_SIZE,
  DEFAULT_PALETTE_COLOR,
  type BrushSize,
  type PaletteColorId,
} from './config';

export interface CanvasPoint {
  x: number;
  y: number;
}

export interface Stroke {
  /**
   * Monotonic, locally-unique id. Lets React keys the renderer hangs off
   * stroke arrays stay stable across undo / redo. Generated by the reducer,
   * not the caller, so tests stay deterministic.
   */
  id: number;
  color: PaletteColorId;
  size: BrushSize;
  points: ReadonlyArray<CanvasPoint>;
}

export interface BrushState {
  color: PaletteColorId;
  size: BrushSize;
  /**
   * Strokes already laid down, oldest first. The current in-progress stroke
   * (if any) is kept in `pending`, not here, so undo/redo never pop a
   * half-drawn line.
   */
  strokes: ReadonlyArray<Stroke>;
  /**
   * The stroke being drawn between pointerdown and pointerup. Cleared on
   * pointer-up commit, on cancel, or when external dispatch tries to begin
   * a fresh stroke without committing the previous one (defensive).
   */
  pending: Stroke | null;
  /**
   * Strokes available for redo. Cleared on every committed stroke (a new
   * branch invalidates older redo history) and on `clear`.
   */
  redoStack: ReadonlyArray<Stroke>;
  /** Counter feeding `Stroke.id`. Test-friendly. */
  nextStrokeId: number;
}

export const initialBrushState: BrushState = {
  color: DEFAULT_PALETTE_COLOR,
  size: DEFAULT_BRUSH_SIZE,
  strokes: [],
  pending: null,
  redoStack: [],
  nextStrokeId: 1,
};

export type BrushAction =
  | { type: 'set-color'; color: PaletteColorId }
  | { type: 'set-size'; size: BrushSize }
  | { type: 'begin-stroke'; point: CanvasPoint }
  | { type: 'extend-stroke'; point: CanvasPoint }
  | { type: 'commit-stroke' }
  | { type: 'cancel-stroke' }
  | { type: 'scale-strokes'; scaleX: number; scaleY: number }
  | { type: 'undo' }
  | { type: 'redo' }
  | { type: 'clear' };

export function brushReducer(
  state: BrushState,
  action: BrushAction,
): BrushState {
  switch (action.type) {
    case 'set-color':
      return { ...state, color: action.color };

    case 'set-size':
      return { ...state, size: action.size };

    case 'begin-stroke': {
      const pending: Stroke = {
        id: state.nextStrokeId,
        color: state.color,
        size: state.size,
        points: [action.point],
      };
      return {
        ...state,
        pending,
        nextStrokeId: state.nextStrokeId + 1,
      };
    }

    case 'extend-stroke': {
      if (!state.pending) return state;
      const pending: Stroke = {
        ...state.pending,
        points: [...state.pending.points, action.point],
      };
      return { ...state, pending };
    }

    case 'commit-stroke': {
      if (!state.pending || state.pending.points.length === 0) {
        return { ...state, pending: null };
      }
      return {
        ...state,
        strokes: [...state.strokes, state.pending],
        pending: null,
        // A new committed stroke creates a new branch — older redo
        // history is no longer reachable from here.
        redoStack: [],
      };
    }

    case 'cancel-stroke':
      return { ...state, pending: null };

    case 'scale-strokes':
      return scaleBrushState(state, action.scaleX, action.scaleY);

    case 'undo': {
      if (state.strokes.length === 0) return state;
      const last = state.strokes[state.strokes.length - 1];
      return {
        ...state,
        strokes: state.strokes.slice(0, -1),
        redoStack: [...state.redoStack, last],
      };
    }

    case 'redo': {
      if (state.redoStack.length === 0) return state;
      const next = state.redoStack[state.redoStack.length - 1];
      return {
        ...state,
        strokes: [...state.strokes, next],
        redoStack: state.redoStack.slice(0, -1),
      };
    }

    case 'clear':
      return {
        ...state,
        strokes: [],
        pending: null,
        redoStack: [],
      };

    default: {
      const _exhaustive: never = action;
      void _exhaustive;
      return state;
    }
  }
}

/** Selector helpers — pure, test-friendly. */
export const selectStrokeCount = (state: BrushState): number =>
  state.strokes.length;

export const selectCanUndo = (state: BrushState): boolean =>
  state.strokes.length > 0;

export const selectCanRedo = (state: BrushState): boolean =>
  state.redoStack.length > 0;

export const selectIsEmpty = (state: BrushState): boolean =>
  state.strokes.length === 0 && state.pending === null;

export function scaleBrushState(
  state: BrushState,
  scaleX: number,
  scaleY: number,
): BrushState {
  if (
    !Number.isFinite(scaleX) ||
    !Number.isFinite(scaleY) ||
    scaleX <= 0 ||
    scaleY <= 0 ||
    (scaleX === 1 && scaleY === 1)
  ) {
    return state;
  }

  return {
    ...state,
    strokes: state.strokes.map((stroke) => scaleStroke(stroke, scaleX, scaleY)),
    pending: state.pending
      ? scaleStroke(state.pending, scaleX, scaleY)
      : null,
    redoStack: state.redoStack.map((stroke) =>
      scaleStroke(stroke, scaleX, scaleY),
    ),
  };
}

function scaleStroke(stroke: Stroke, scaleX: number, scaleY: number): Stroke {
  return {
    ...stroke,
    points: stroke.points.map((point) => ({
      x: point.x * scaleX,
      y: point.y * scaleY,
    })),
  };
}
